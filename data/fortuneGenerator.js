function createFortune(isLove = false) {
  const category = isLove ? 'love' : 'general';
  const result = pick(isLove ? loveFortunes : fortunes, category + ':result', 4);
  const message = pick(result.messages, category + ':message', 3);
  const question = pick(isLove ? loveQuestions : questions, category + ':question', 8);
  const advice = pick(isLove ? loveAdvices : advices, category + ':advice', 8);
  const tangent = pick(isLove ? loveTangents : tangents, category + ':tangent', 6);
  const closing = pick(closings, 'closing', 8);
  const opening = Math.random() < 0.72 ? pick(openings, 'opening', 8) : '';
  const body = [
    opening ? opening + question : question,
    advice,
    Math.random() < 0.65 ? tangent : null,
    Math.random() < 0.30 ? pick(rpgInvitations, 'rpg', 8) : null,
    closing
  ].filter(Boolean);

  return {
    title: isLove ? '恋みくじ' : '和紙の運勢',
    name: result.name,
    description: message + '\n\n' + body.join('\n\n'),
    color: result.color,
    footer: pick(footerTexts, 'footer', 6)
  };
}

