const recentPicks = new Map();

function pick(items, key, historySize = 8) {
  if (!items.length) return '';
  const recent = recentPicks.get(key) || [];
  const available = items.filter((item) => !recent.includes(item));
  const selected = available[Math.floor(Math.random() * available.length)] || items[Math.floor(Math.random() * items.length)];
  recentPicks.set(key, [...recent.filter((item) => item !== selected), selected].slice(-historySize));
  return selected;
}

